create or replace function public.activate_enrolment_after_payment_verification() returns trigger
language plpgsql security definer set search_path='' as $$
declare v_enrollment_id bigint;
begin
 if new.status='verified' and old.status is distinct from 'verified' then
  -- The existing unique(student_id, course_id) constraint means a pending row
  -- must be activated rather than inserting a second row for the same student/course.
  insert into public.enrollments(student_id,course_id,enrollment_status,enrollment_type)
  values(new.student_id,new.course_id,'active','paid')
  on conflict(student_id,course_id) do update
    set enrollment_status='active', enrollment_type='paid'
  returning id into v_enrollment_id;

  update public.payments set enrollment_id=v_enrollment_id
  where id=new.id and enrollment_id is distinct from v_enrollment_id;
 end if;
 return new;
end;
$$;
drop trigger if exists trg_activate_enrolment_after_payment_verification on public.payments;
