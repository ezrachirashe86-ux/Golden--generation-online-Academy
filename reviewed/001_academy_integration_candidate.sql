create or replace function public.request_course_payment(p_course_id bigint) returns bigint
language plpgsql security definer set search_path='' as $$
declare v_id bigint; v_price numeric; v_currency text; v_published boolean; v_role text;
begin
 if auth.uid() is null then raise exception 'Sign in is required.'; end if;
 select role into v_role from public.profiles where id=auth.uid();
 if v_role is distinct from 'student' then raise exception 'Only student accounts can request payment.'; end if;
 if not exists(select 1 from public.academy_payment_settings where id=1 and enabled=true) then raise exception 'Payment instructions are not enabled.'; end if;
 select price,currency,published into v_price,v_currency,v_published from public.courses where id=p_course_id;
 if not found or v_published is distinct from true then raise exception 'Course is unavailable.'; end if;
 if coalesce(v_price,0)<=0 then raise exception 'This course does not require payment.'; end if;
 if exists(select 1 from public.enrollments where student_id=auth.uid() and course_id=p_course_id and enrollment_status='active') then raise exception 'You are already enrolled.'; end if;
 if exists(select 1 from public.payments where student_id=auth.uid() and course_id=p_course_id and status in ('pending','submitted','under_review','verified')) then raise exception 'A payment request already exists.'; end if;
 insert into public.payments(student_id,course_id,amount,currency,payment_method,status) values(auth.uid(),p_course_id,v_price,coalesce(v_currency,'ZAR'),'eft','pending') returning id into v_id;
 return v_id;
end $$;
